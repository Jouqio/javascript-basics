const id = 123;
let username = "Syauqi Nuzul Abdi";

console.log(id); // output: 123
console.log(username); //output: Syauqi Nuzul Abdi

//Kode di atas merupakan contoh membuat variabel. Pada contoh tersebut,
// variabel bernama id dibuat menggunakan const dan variabel bernama username dibuat dengan let.
// Perbedaan dari variabel yang dibuat dengan const dan
// let adalah variabel yang dibuat dengan const tidak dapat diinisialisasi ulang
// (sederhananya, diubah) nilainya, sedangkan jika variabel dibuat dengan let, kita bisa menginisialisasi ulang nilainya.
// Bayangkan const seperti nomor telepon darurat, misalnya nomor 911. Nomor ini selalu sama
// dan tidak berubah untuk menjaga konsistensi dan keandalan dalam keadaan darurat. Demikian pula,
// variabel yang dideklarasikan dengan const tidak dapat diubah setelah diinisialisasi.
// Nomor darurat adalah sesuatu yang tidak Anda ingin ubah, sama halnya dengan const dalam kode Anda.
// Sementara itu, bayangkan let seperti papan tulis di ruang kelas.
// Anda dapat menulis sesuatu di papan tulis, dan jika perlu, Anda bisa menghapus dan menuliskan
// sesuatu yang baru. Dengan cara yang sama, variabel yang dideklarasikan dengan let dapat diubah atau diperbarui nilainya setelah inisialisasi pertama. //

