//Contoh, ketika membuat variabel dengan let, Anda bisa mengubah nilai yang ada di dalamnya setelah variabel tersebut dibuat.//

let username = 'Jouqio';

console.log('Sebelum diubah:', username); // output: Sebelum diubah: Jouqio

username = 'Syauqi Nuzul Abdi';

console.log('Setelah diubah:', username); // output: Setelah diubah: Syauqi Nuzul Abdi